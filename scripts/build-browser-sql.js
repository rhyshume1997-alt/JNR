'use strict';
// Builds db/browser-setup.sql: ONE self-contained SQL file that does what `npm run migrate` does, so the database can be set
// up by pasting it into a browser SQL editor (for example Neon's) with no terminal. It contains no secrets.
//   node scripts/build-browser-sql.js            writes db/browser-setup.sql
//   node scripts/build-browser-sql.js --check    fails if the file is out of date (a test runs this)
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', 'db', 'migrations');
const out = path.join(__dirname, '..', 'db', 'browser-setup.sql');

function build() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  let s = '-- JNR workshop content system: complete database setup in ONE file, for a browser SQL editor (no terminal needed).\n' +
    '-- GENERATED by scripts/build-browser-sql.js from db/migrations/*.sql. Do not edit by hand. Contains no secrets.\n' +
    '--\n' +
    '-- HOW TO RUN: Neon console > your project > SQL Editor > choose the database (neondb) > paste this whole file > Run.\n' +
    '-- Safe to run once. If the tables already exist it stops with a clear message and changes nothing.\n' +
    '-- It records itself in schema_migrations, so `npm run migrate` later will skip these files instead of repeating them.\n\n' +
    'begin;\n\n' +
    '-- Stop if this has already been run.\n' +
    'do $guard$ begin\n  if to_regclass(\'public.entries\') is not null then\n    raise exception \'JNR setup has already been run on this database. Nothing was changed.\';\n  end if;\nend $guard$;\n\n' +
    'create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());\n\n';
  for (const f of files) s += '-- ===== ' + f + ' =====\n' + fs.readFileSync(path.join(dir, f), 'utf8').trim() + '\n\n';
  s += '-- Record the files as applied.\ninsert into schema_migrations (name) values ' + files.map((f) => "('" + f + "')").join(', ') + ' on conflict do nothing;\n\ncommit;\n';
  return s;
}

module.exports = { build, out };
if (require.main === module) {
  const s = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== s) { console.error('db/browser-setup.sql is out of date. Run: node scripts/build-browser-sql.js'); process.exit(1); }
    console.log('db/browser-setup.sql is up to date.');
  } else { fs.writeFileSync(out, s); console.log('Wrote ' + out + ' (' + s.length + ' bytes)'); }
}
