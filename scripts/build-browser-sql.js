'use strict';
// Builds db/browser-setup.sql: ONE self-contained SQL file that does what `npm run migrate` does, so the database can be set
// up by pasting it into a browser SQL editor (for example Neon's) with no terminal. It contains no secrets.
//   node scripts/build-browser-sql.js            writes db/browser-setup.sql
//   node scripts/build-browser-sql.js --check    fails if the file is out of date (a test runs this)
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', 'db', 'migrations');
const out = path.join(__dirname, '..', 'db', 'browser-setup.sql');
const FIRST_SETUP_FILES = ['001_workshop_content.sql', '002_lock_down_tables.sql'];   // what browser-setup.sql has always contained

function build() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  let s = '-- JNR workshop content system: complete database setup in ONE file, for a browser SQL editor (no terminal needed).\n' +
    '-- GENERATED by scripts/build-browser-sql.js from db/migrations/*.sql. Do not edit by hand. Contains no secrets.\n' +
    '--\n' +
    '-- HOW TO RUN: Neon console > your project > SQL Editor > choose the database (neondb) > paste this whole file > Run.\n' +
    '-- Safe to run once. If the tables already exist it stops with a clear message and changes nothing.\n' +
    '-- It records itself in schema_migrations, so `npm run migrate` later will skip these files instead of repeating them.\n\n' +
    'begin;\n\n' +
    '-- Stop if this has already been run.\n' +
    'do $guard$ begin\n  if to_regclass(\'public.entries\') is not null then\n    raise exception \'JNR setup has already been run on this database. Nothing was changed.\';\n  end if;\nend $guard$;\n\n' +
    'create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());\n\n';
  for (const f of files) s += '-- ===== ' + f + ' =====\n' + fs.readFileSync(path.join(dir, f), 'utf8').trim() + '\n\n';
  s += '-- Record the files as applied.\ninsert into schema_migrations (name) values ' + files.map((f) => "('" + f + "')").join(', ') + ' on conflict do nothing;\n\ncommit;\n';
  return s;
}

// For a database that already ran browser-setup.sql: one small file per later migration. It refuses to run if the earlier setup is
// missing, or if this migration was already applied, and records itself in schema_migrations.
function upgradeFiles() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  return files.filter((f) => !FIRST_SETUP_FILES.includes(f)).map((f) => {
    const n = f.slice(0, 3);
    const name = path.join(__dirname, '..', 'db', 'browser-upgrade-' + n + '.sql');
    const text = '-- JNR workshop content system: database UPGRADE ' + f + ' for a browser SQL editor (no terminal needed).\n' +
      '-- GENERATED by scripts/build-browser-sql.js from db/migrations/' + f + '. Do not edit by hand. Contains no secrets.\n' +
      '--\n' +
      '-- HOW TO RUN: Neon console > your project > SQL Editor > choose the database (neondb) > paste this whole file > Run.\n' +
      '-- For a database that already ran db/browser-setup.sql. Safe to run once: it stops with a clear message if the first setup is\n' +
      '-- missing or this upgrade was already applied, and changes nothing in that case. It records itself in schema_migrations.\n\n' +
      'begin;\n\n' +
      'do $guard$ begin\n  if to_regclass(\'public.entries\') is null or to_regclass(\'public.schema_migrations\') is null then\n    raise exception \'The first JNR setup (db/browser-setup.sql) has not been run on this database. Nothing was changed.\';\n  end if;\n' +
      '  if exists (select 1 from schema_migrations where name = \'' + f + '\') then\n    raise exception \'This upgrade (' + f + ') has already been run on this database. Nothing was changed.\';\n  end if;\nend $guard$;\n\n' +
      '-- ===== ' + f + ' =====\n' + fs.readFileSync(path.join(dir, f), 'utf8').trim() + '\n\n' +
      "insert into schema_migrations (name) values ('" + f + "');\n\ncommit;\n";
    return { name, text };
  });
}

module.exports = { build, out, upgradeFiles };
if (require.main === module) {
  const s = build();
  const ups = upgradeFiles();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== s) { console.error('db/browser-setup.sql is out of date. Run: node scripts/build-browser-sql.js'); process.exit(1); }
    for (const u of ups) {
      const c = fs.existsSync(u.name) ? fs.readFileSync(u.name, 'utf8') : '';
      if (c !== u.text) { console.error(path.basename(u.name) + ' is out of date. Run: node scripts/build-browser-sql.js'); process.exit(1); }
    }
    console.log('db/browser-setup.sql and the upgrade files are up to date.');
  } else {
    fs.writeFileSync(out, s); console.log('Wrote ' + out + ' (' + s.length + ' bytes)');
    for (const u of ups) { fs.writeFileSync(u.name, u.text); console.log('Wrote ' + u.name); }
  }
}
